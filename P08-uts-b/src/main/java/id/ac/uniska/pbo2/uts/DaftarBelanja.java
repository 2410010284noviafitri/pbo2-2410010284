   private void tambah() {
    String nama = namaField.getText().trim();
   String salah = validasiNama(nama);
    if (salah == null && model.sudahAda(nama)) {
        salah = "Barang " + nama + " sudah ada di daftar";
    }
    if (salah != null) { tampilkanKesalahan(salah, namaField); return; }

    salah = validasiHarga(hargaField.getText());
    if (salah != null) { tampilkanKesalahan(salah, hargaField); return; }

    model.tambah(new Barang(nama, (Kategori) kategoriCombo.getSelectedItem(),
            Integer.parseInt(hargaField.getText().trim()),
            (Integer) jumlahSpinner.getValue()));
    bersihkan();
    tampilkanTotal();
}

private void tampilkanKesalahan(String pesan, javax.swing.JComponent isian) {
    pesanLabel.setText(pesan);
    isian.requestFocusInWindow();
}

private void bersihkan() {
    namaField.setText("");
    hargaField.setText("");
    kategoriCombo.setSelectedIndex(0);
    jumlahSpinner.setValue(1);
    pesanLabel.setText("");
    namaField.requestFocusInWindow();
}

private String validasiNama(String nama) {
    return nama.isBlank() ? "Nama barang wajib diisi" : null;
}

private String validasiHarga(String harga) {
    String salah = "Harga harus angka 1 sampai 10000000";
    String h = harga.trim();
    if (!h.matches("\\d{1,8}")) return salah;
    long nilai = Long.parseLong(h);
    return (nilai < 1 || nilai > 10000000) ? salah : null;
}
private void tampilkanTotal() {
    totalLabel.setText("Total " + BelanjaTableModel.rupiah(model.getTotal())
        + ", diskon " + BelanjaTableModel.rupiah(model.getDiskon())
        + ", bayar " + BelanjaTableModel.rupiah(model.getBayar()));
}  
